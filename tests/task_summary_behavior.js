const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..'),src=fs.readFileSync(path.join(root,'webui/nx.js'),'utf8');
const begin=src.indexOf('// TASK SUMMARY START'),end=src.indexOf('// TASK SUMMARY END');
assert(begin>=0&&end>begin,'Görev sonuç kartı yardımcıları bulunamadı');
const notices=[],c={S:{page:'chat',snap:{user:{slug:'alice'}},steps:{},live:[]},Map,drawMsgs:()=>{},
  esc:x=>String(x).replace(/[&<>"']/g,x=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[x])),
  ACT:{},toast:t=>notices.push(t),tryApi:async name=>{assert.equal(name,'stop_task');return {stopped:true,msg:'Durduruldu'}}};
vm.createContext(c);
vm.runInContext(src.slice(begin,end),c);
const plain=x=>JSON.parse(JSON.stringify(x));
let job={title:'Rapor',state:'cancelled',steps:[{text:'Kaynak oku',state:'done'},{text:'Rapor yaz',state:'working'}]};
assert.deepEqual(plain(c.taskSummaryData(job)),{title:'Rapor',done:['Kaynak oku'],left:['Rapor yaz'],stopped:true,verified:false});
assert.equal(c.taskSummaryData({title:'x',state:'done',steps:[{text:'a',state:'done'}]}).verified,false);
assert.equal(c.taskSummaryData({title:'x',state:'done',verified:true,steps:[{text:'a',state:'done'}]}).verified,true);
for(const bad of [null,[],{},false,{title:2,state:'done',steps:[]},{title:'x',state:'done',steps:[null]}])
  assert.deepEqual(plain(c.taskSummaryData(bad)),{title:'',done:[],left:[],stopped:false,verified:false});
assert(!c.taskSummaryHtml({title:'<img src=x onerror=bad>',state:'done',steps:[{text:'<script>bad</script>',state:'done'}]}).includes('<script>'));
assert(c.taskSummaryHtml(job).includes('Yarım kalan'));
const secret='token=PRIVATE_SECRET_VALUE alice@example.org';
assert(!c.taskSummaryHtml({title:secret,state:'done',steps:[{text:secret,state:'done'}]}).includes('PRIVATE'));
assert(!c.taskSummaryText(secret).includes('alice@example.org'));
assert.equal(c.taskSummaryText('ş'.repeat(201)).length,200);
for(const value of ['şifre=PRIVATE_SECRET_VALUE','ŞİFRE: PRIVATE_SECRET_VALUE','parola: PRIVATE_SECRET_VALUE','refresh_token=PRIVATE_SECRET_VALUE','access_token=PRIVATE_SECRET_VALUE','belirteç=PRIVATE_SECRET_VALUE'])assert(!c.taskSummaryText(value).includes('PRIVATE'),value);
const card=(owner='alice')=>({ts:1,_summaryOwner:owner,_summaryReady:false,items:new Map([['s1',{t:'Oku',s:'done'}],['s2',{t:'Yaz',s:'working'}]])});
c.S.steps.r1=card();
assert.equal(c.taskSummaryActiveRid(),'r1');
c.taskSummaryEvent({k:'state',t:'thinking',user:'alice'});
c.taskSummaryEvent({k:'state',t:'idle',user:'alice'});
assert(!c.S.steps.r1._summaryReady,'mikrofonun kimliksiz idle olayı görevi bitirmez');
assert(!c.taskSummaryCardHtml(c.S.steps.r1));
c.taskSummaryEvent({k:'assistant',rid:'r1',user:'bob'});
assert(!c.taskSummaryCardHtml(c.S.steps.r1),'başka kullanıcının olayı işi bitiremez');
c.taskSummaryEvent({k:'state',t:'idle',rid:'r1',user:'alice'});
assert(c.taskSummaryCardHtml(c.S.steps.r1).includes('Görev sonucu'));
assert(c.taskSummaryCardHtml(c.S.steps.r1).includes('Doğrulama bilgisi yok'));
c.S.steps.final=card();
c.taskSummaryEvent({k:'assistant',rid:'final',user:'alice'});
assert(c.S.steps.final._summaryReady,'aynı istek kimliğinin yanıtı sonuç kartı üretir');
c.S.snap.user.slug='bob';
assert.equal(c.taskSummaryCardHtml(c.S.steps.r1),'','kullanıcı değişince eski kart görünmez');
c.S.snap.user.slug='alice';
c.S.steps={r1:card(),r2:card()};
c.taskSummaryEvent({k:'state',t:'idle',user:'alice'});
assert(!c.S.steps.r1._summaryReady&&!c.S.steps.r2._summaryReady,'kimliksiz olay eşzamanlı işleri bitiremez');
c.S.live=[{role:'user',rid:'r2'}];
assert.equal(c.taskSummaryActiveRid(),'r2');
c.S.steps={r1:card()};c.S.live=[{role:'user',rid:'new-without-steps'}];
assert.equal(c.taskSummaryActiveRid(),null,'yeni isteğin adımı yokken eski kart durdurulmaz');
const stop=src.match(/ACT\.stoptask=async\(\)=>\{[\s\S]*?\n?\};/);
assert(stop,'mevcut Durdur yolu korunmalı');
vm.runInContext(stop[0],c);
(async()=>{
  c.S.steps={r1:card()};c.S.live=[];
  await c.ACT.stoptask();
  assert.equal(c.S.steps.r1._summaryStopped,true);
  assert(c.taskSummaryCardHtml(c.S.steps.r1).includes('Durdurulan görev'));
  assert(c.taskSummaryCardHtml(c.S.steps.r1).includes('Yaz'));
  c.S.steps={r1:card()};
  c.tryApi=async()=>null;
  await c.ACT.stoptask();
  assert(!c.S.steps.r1._summaryReady,'başarısız durdurma başarı kartı üretmez');
  c.S.steps={r1:card()};c.S.live=[];
  c.tryApi=async()=>{c.taskSummaryEvent({k:'state',t:'idle',user:'alice'});return {stopped:true}};
  await c.ACT.stoptask();
  assert.equal(c.S.steps.r1._summaryStopped,true,'idle olayı API yanıtından önce gelebilir');
  c.S.steps={r1:card()};
  let finish;
  c.tryApi=()=>new Promise(resolve=>{finish=resolve});
  const pending=c.ACT.stoptask();
  c.S.steps.r2=card();c.S.live=[{role:'user',rid:'r2'}];
  finish({stopped:true});
  await pending;
  assert.equal(c.S.steps.r1._summaryStopped,true);
  assert(!c.S.steps.r2._summaryReady,'gecikmiş durdurma yanıtı yeni işi kapatamaz');
  // Successful substeps are not completion: onStep never sets summaryReady=true.
  const track=src.slice(src.indexOf('function onStep('),src.indexOf('// Mesaj başındaki'));
  assert(track.includes('taskSummaryTrack(card,rid)'),'gerçek onStep bağlantısı gerekli');
  assert(src.includes('taskSummaryEvent(m);'),'gerçek olay akışı bağlantısı gerekli');
  assert(src.includes('taskSummaryCardHtml(card)'),'gerçek sohbet kartı bağlantısı gerekli');
  const css=fs.readFileSync(path.join(root,'webui/nx.css'),'utf8');
  assert(css.includes('.task-summary'),'kartın yerel stili bulunmalı');
  console.log('OK task summary behavior');
})().catch(e=>{console.error(e);process.exitCode=1});
